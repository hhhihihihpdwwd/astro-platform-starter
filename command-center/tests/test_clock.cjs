const assert=require('node:assert/strict');
const C=require('../lib/clock.js');
const midday=new Date('2026-06-21T12:00:00Z');
const midnight=new Date('2026-06-21T00:00:00Z');
assert.equal(C.CITIES.length,4);
assert.equal(C.cityTime(new Date('2026-11-23T12:00:07Z'),'Europe/Berlin').time,'13:00:07');
assert.equal(C.cityTime(new Date('2026-11-23T12:00:07Z'),'America/New_York').time,'07:00:07');
assert.equal(C.cityTime(new Date('2026-11-23T12:00:07Z'),'Europe/London').time,'12:00:07');
assert.equal(C.cityTime(new Date('2026-11-23T12:00:07Z'),'Australia/Sydney').time,'23:00:07');
assert.equal(C.greeting(new Date('2026-11-23T08:00:00Z')),'Guten Morgen');
assert.equal(C.greeting(new Date('2026-11-23T12:00:00Z')),'Guten Tag');
assert.equal(C.greeting(new Date('2026-11-23T20:00:00Z')),'Guten Abend');
assert(C.solarElevation(midday)>45,'Midsummer noon in Hamburg must have high sun');
assert(C.solarElevation(midnight)<0,'Sun must be below horizon overnight');
assert(C.sunMood(midday).visible);
const morningSolar=C.solarDay(new Date('2026-06-21T07:00:00Z'));
assert(morningSolar.sunrise instanceof Date && morningSolar.sunset instanceof Date);
assert(morningSolar.sunrise.getTime()<morningSolar.sunset.getTime());
assert(morningSolar.progress>0 && morningSolar.progress<1);
assert(C.CITIES.every(c=>Number.isFinite(c.lon)&&Number.isFinite(c.lat)));
assert(!C.CITIES.some(c=>c.id==='capecod'));
console.log('OK: 16 solar/timezone/geo tests');
